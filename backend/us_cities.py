def lookup_coords(city: str, state: str):
    """Return (lat, lng) from static dict or state centroid fallback.

    Tries exact key first, then title-cased city, then state centroid.
    Returns (None, None) if state is also unknown.
    """
    st = state.strip().upper()
    c = city.strip()

    key = f"{c},{st}"
    if key in US_CITIES:
        return US_CITIES[key]

    # Try title-casing the city name
    key2 = f"{c.title()},{st}"
    if key2 in US_CITIES:
        return US_CITIES[key2]

    # State centroid fallback
    centroid = STATE_CENTROIDS.get(st)
    if centroid:
        return centroid

    return None, None
